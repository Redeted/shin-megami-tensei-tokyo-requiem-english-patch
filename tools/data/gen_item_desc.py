# Equipment descriptions for item_desc.tsv, from the 30-byte item records (same fields as EquipSetDraw).
# usage: gen_item_desc.py <megaten001.bin> <names_item.tsv>  -> stdout
import sys

HITS = ["-", "1", "2", "0-1", "0-2", "1-2", "1-3", "2-3", "2-4", "2-8",
        "3-5", "3-6", "5-8", "all foes", "0-8", "all", "0"]
RES = [None, None, "Fire Res", "Fire Res+", "Ice Res", "Ice Res+", "Elec Res", "Force Res",
       "Elec/Fire Res", "Psy Res", "Res All", "Drains Elec", "Insulated", "Holy armor"]
BONUS = [None, "St +1", "St +2", "St +3", "In +1", "In +2", "In +3", "Ma +1", "Ma +2", "Ma +3",
         "Vi +1", "Vi +2", "Vi +3", "Ag +1", "Ag +2", "Ag +3", "Lu +1", "Lu +2", "Lu +3", "St +1, Vi +1",
         "St +3, Ag +1", "In +1, Ma +2", "In +1, Ma +3", "Ag +1, Lu +1", "All stats +1", "All stats +2", "CURSED",
         "St +3, CURSED", "Ma +3, CURSED", "Vi +3, CURSED"]
ALIGN = [None, "Law only", "Neutral only", "Chaos only"]
SLOT = {3: "Head", 4: "Body", 5: "Arms", 6: "Legs"}

d = open(sys.argv[1], "rb").read()
names = {}
for l in open(sys.argv[2], encoding="utf-8"):
    p = l.rstrip("\n").split("\t")
    if not l.startswith("#") and len(p) >= 3:
        names[int(p[0])] = p[2]
print("# Shop item descriptions (ShopDescPatch): @desc.item.{id} TAB text. Two lines, max 34 half-width chars each (check_item_desc.py); equipment uses an explicit line break.")
print("# --- Equipment: generated by gen_item_desc.py from the item data (Atk/Hit/Hits = EquipSetDraw's weapon box,")
print("#     Def/Eva/Res = its armor box; bonus = ParamUpType; \"X only\" = the Align field).")
for i in range(1, 103):
    b = d[0xd335 + i * 30: 0xd335 + i * 30 + 30]
    kind, align = b[17] & 0xF, (b[17] >> 4) & 3
    bonus, a, h, f = BONUS[b[18] & 0x1F], b[19], b[20], b[21]
    if kind == 1:
        line1 = f"Atk {a}  Hit +{h}  Hits {HITS[f]}"
        rest = []
    else:
        line1 = f"{SLOT[kind]}  Def {a}  Eva +{h}"
        rest = []
        if RES[f]:
            if len(line1) + 2 + len(RES[f]) <= 34: line1 += "  " + RES[f]
            else: rest.append(RES[f])
    rest += [x for x in (bonus, ALIGN[align]) if x]
    # two lines of at most 34 half-width chars: if line 2 is too long, move "X only" up to line 1
    if len("  ".join(rest)) > 34 and ALIGN[align] and len(line1) + 2 + len(ALIGN[align]) <= 34:
        rest.remove(ALIGN[align])
        line1 += "  " + ALIGN[align]
    text = line1 + ("\\n" +"  ".join(rest) if rest else "")
    print(f"@desc.item.{i}	{text}	{names.get(i, '?')}")
